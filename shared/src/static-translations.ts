export function translateStaticText(language: AppLanguage, value: string) {
  if (language !== "hi") return value;
  const trimmed = value.trim();
  return staticText[trimmed as keyof typeof staticText] ?? localizeKnownEnglish(language, trimmed);
}

export function translateStaticChildren(language: AppLanguage, children: ReactNode): ReactNode {
  if (language !== "hi") return children;
  if (typeof children === "string") return translateStaticText(language, children);
  if (Array.isArray(children)) {
    return children.map((child) => translateStaticChildren(language, child));
  }
  return children;
}
