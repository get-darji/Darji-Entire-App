export function translateStaticText(language: AppLanguage, value: string) {
  if (language !== "hi") return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const trimmed = value.trim();
  if (!trimmed) return value;
  const translated = translateStaticCore(language, trimmed);
  return `${leading}${translated}${trailing}`;
}

function isCorruptedHindi(value: string) {
  const questionMarks = (value.match(/\?/g) ?? []).length;
  return questionMarks >= 3 || value.includes("\uFFFD");
}

function translateStaticCore(language: AppLanguage, value: string): string {
  const direct = staticText[value as keyof typeof staticText] ?? generatedHindiUi[value as keyof typeof generatedHindiUi] ?? localizeKnownEnglish(language, value);
  if (isCorruptedHindi(direct)) return value;
  if (direct !== value) return direct;

  const otpCooldownMatch = value.match(/^Please wait (\d+) seconds before requesting another OTP\.$/);
  if (otpCooldownMatch) return `अगला ओटीपी माँगने से पहले ${otpCooldownMatch[1]} सेकंड प्रतीक्षा करें।`;

  const countMatch = value.match(/^(\d+)\s+(.+)$/);
  if (countMatch) {
    const [, count, rest] = countMatch;
    const translatedRest = translateStaticCore(language, rest);
    if (translatedRest !== rest) return `${count} ${translatedRest}`;
  }

  const colonMatch = value.match(/^([^:]+):\s*(.+)$/);
  if (colonMatch) {
    const [, label, rest] = colonMatch;
    const translatedLabel = translateStaticCore(language, label);
    const translatedRest = translateStaticCore(language, rest);
    if (translatedLabel !== label || translatedRest !== rest) return `${translatedLabel}: ${translatedRest}`;
  }

  const slashMatch = value.match(/^([^/]+)\s*\/\s*([^/]+)$/);
  if (slashMatch) {
    const [, left, right] = slashMatch;
    const translatedLeft = translateStaticCore(language, left.trim());
    const translatedRight = translateStaticCore(language, right.trim());
    if (translatedLeft !== left.trim() || translatedRight !== right.trim()) return `${translatedLeft} / ${translatedRight}`;
  }

  return value;
}

export function translateStaticChildren(language: AppLanguage, children: ReactNode): ReactNode {
  if (language !== "hi") return children;
  if (typeof children === "string") return translateStaticText(language, children);
  if (Array.isArray(children)) {
    return children.map((child) => translateStaticChildren(language, child));
  }
  return children;
}
